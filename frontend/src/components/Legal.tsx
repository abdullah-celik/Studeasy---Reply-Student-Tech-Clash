const TITLES: Record<LegalDoc, string> = { terms: "Terms of Use", privacy: "Privacy Policy" };

export function LegalDialog({ doc, onClose }: { doc: LegalDoc | null; onClose: () => void }) {
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (doc && !d.open) d.showModal();
    if (!doc && d.open) d.close();
  }, [doc]);

  return (
    <dialog
      ref={ref}
      className="legal"
      onClose={onClose}
      onClick={(e) => {
        if (e.target === ref.current) onClose(); // click on the backdrop
      }}
      aria-labelledby="legal-title"
    >
      {doc && (
        <div className="legal-inner">
          <div className="legal-head">
            <h2 id="legal-title">{TITLES[doc]}</h2>
            <button className="mini" aria-label="Close" onClick={onClose}>
              <PixelIcon name="close" size={12} />
            </button>
          </div>
          <div className="legal-body">{doc === "terms" ? <Terms /> : <Privacy />}</div>
          <div className="legal-foot">
            <button onClick={onClose}>Got it</button>
          </div>
        </div>
      )}
    </dialog>
  );
}

/** "Terms of Use · Privacy Policy" links that open the dialog. */
export function LegalLinks({ open, children, sep = " · " }: { open: (d: LegalDoc) => void; children?: ReactNode; sep?: string }) {
  return (
    <span className="legal-links">
      {children}
      <button type="button" className="link" onClick={() => open("terms")}>Terms of Use</button>
      {sep}
      <button type="button" className="link" onClick={() => open("privacy")}>Privacy Policy</button>
    </span>
  );
}
